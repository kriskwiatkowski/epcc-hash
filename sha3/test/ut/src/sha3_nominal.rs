//! Correctness tests and benchmarks for `epcc_keccak`, shared between
//! `cargo test` (via the `#[test]` fns below) and the embedded runtimes
//! under `runtime/`, which run the same checks on-device through the
//! plain-fn [`TESTS`]/[`BENCHMARKS`] tables.

use epcc_keccak::{sha3::sha3_256, sha3::sha3_512};

pub(crate) fn test_sha3_known_answer() {
    let hash = sha3_256(b"");
    assert_eq!(
        hash,
        [
            0xa7, 0xff, 0xc6, 0xf8, 0xbf, 0x1e, 0xd7, 0x66, 0x51, 0xc1, 0x47,
            0x56, 0xa0, 0x61, 0xd6, 0x62, 0xf5, 0x80, 0xff, 0x4d, 0xe4, 0x3b,
            0x49, 0xfa, 0x82, 0xd8, 0x0a, 0x4b, 0x80, 0xf8, 0x43, 0x4a
        ]
    );
    let hash = sha3_512(b"");
    assert_eq!(
        hash,
        [
            0xa6, 0x9f, 0x73, 0xcc, 0xa2, 0x3a, 0x9a, 0xc5, 0xc8, 0xb5, 0x67,
            0xdc, 0x18, 0x5a, 0x75, 0x6e, 0x97, 0xc9, 0x82, 0x16, 0x4f, 0xe2,
            0x58, 0x59, 0xe0, 0xd1, 0xdc, 0xc1, 0x47, 0x5c, 0x80, 0xa6, 0x15,
            0xb2, 0x12, 0x3a, 0xf1, 0xf5, 0xf9, 0x4c, 0x11, 0xe3, 0xe9, 0x40,
            0x2c, 0x3a, 0xc5, 0x58, 0xf5, 0x00, 0x19, 0x9d, 0x95, 0xb6, 0xd3,
            0xe3, 0x01, 0x75, 0x85, 0x86, 0x28, 0x1d, 0xcd, 0x26
        ]
    );
    let hash = sha3_256(b"a");
    assert_eq!(
        hash,
        [
            0x80, 0x08, 0x4b, 0xf2, 0xfb, 0xa0, 0x24, 0x75, 0x72, 0x6f, 0xeb,
            0x2c, 0xab, 0x2d, 0x82, 0x15, 0xea, 0xb1, 0x4b, 0xc6, 0xbd, 0xd8,
            0xbf, 0xb2, 0xc8, 0x15, 0x12, 0x57, 0x03, 0x2e, 0xcd, 0x8b
        ]
    );
    let hash = sha3_512(b"a");
    assert_eq!(
        hash,
        [
            0x69, 0x7f, 0x2d, 0x85, 0x61, 0x72, 0xcb, 0x83, 0x09, 0xd6, 0xb8,
            0xb9, 0x7d, 0xac, 0x4d, 0xe3, 0x44, 0xb5, 0x49, 0xd4, 0xde, 0xe6,
            0x1e, 0xdf, 0xb4, 0x96, 0x2d, 0x86, 0x98, 0xb7, 0xfa, 0x80, 0x3f,
            0x4f, 0x93, 0xff, 0x24, 0x39, 0x35, 0x86, 0xe2, 0x8b, 0x5b, 0x95,
            0x7a, 0xc3, 0xd1, 0xd3, 0x69, 0x42, 0x0c, 0xe5, 0x33, 0x32, 0x71,
            0x2f, 0x99, 0x7b, 0xd3, 0x36, 0xd0, 0x9a, 0xb0, 0x2a
        ]
    );
    let hash = sha3_256(b"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa");
    assert_eq!(
        hash,
        [
            0x2e, 0xee, 0x42, 0xb2, 0x99, 0xcb, 0x44, 0xbb, 0x3d, 0x5d, 0xd0,
            0xa0, 0x22, 0x10, 0xce, 0x29, 0xde, 0xbc, 0x21, 0x10, 0xb7, 0xc4,
            0x64, 0x4f, 0xf3, 0x8c, 0x53, 0x08, 0x49, 0x40, 0xbe, 0x21
        ]
    );
    let hash = sha3_512(b"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa");
    assert_eq!(
        hash,
        [
            0x9b, 0x6d, 0x61, 0x98, 0xa1, 0x73, 0xac, 0xf0, 0x76, 0x30, 0x1e,
            0xf0, 0xa0, 0xd1, 0x02, 0x77, 0x2d, 0x71, 0x7b, 0x10, 0x12, 0x49,
            0xe3, 0x7b, 0x1e, 0x85, 0x93, 0x92, 0x7d, 0xa3, 0x94, 0x21, 0xdf,
            0x5c, 0x95, 0x6f, 0x8a, 0xf3, 0xd1, 0xf1, 0x02, 0xba, 0x3a, 0x05,
            0x05, 0xc1, 0xae, 0x9c, 0x62, 0x1c, 0x04, 0xb3, 0xf5, 0x7f, 0x46,
            0x6d, 0x1e, 0x5a, 0x00, 0x25, 0xd9, 0xba, 0x92, 0xdd
        ]
    );
}

#[cfg(test)]
#[test]
fn sha3_known_answer() {
    test_sha3_known_answer();
}
